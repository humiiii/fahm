def text(x,y,s,size=12,color=INK,bold=False):
    c.setFont('Bold' if bold else 'Body',size); c.setFillColor(color); c.drawString(x,y,s)

def para(x,y,s,w,size=13,leading=19,color=MUTED):
    for line in simpleSplit(s,'Body',size,w): text(x,y,line,size,color); y-=leading
    return y

def box(x,y,w,h,title,body,accent=False):
    c.setStrokeColor(BLUE if accent else LINE); c.setLineWidth(.9)
    c.setFillColor(HexColor('#eef1ff') if accent else HexColor('#ffffff'))
    c.roundRect(x,y,w,h,8,fill=1,stroke=1)
    text(x+18,y+h-28,title,17,BLUE if accent else INK,True)
    size, leading = 13, 19
    while h-50-(len(simpleSplit(body,'Body',size,w-36))-1)*leading < 13 and size > 11:
        size -= .5; leading -= 1
    end=para(x+18,y+h-50,body,w-36,size,leading)
    assert end+leading >= y+12, (title,'overflow',end,y)

def arrow(points,label=None,lx=0,ly=0,dashed=False):
    c.setStrokeColor(BLUE); c.setFillColor(BLUE); c.setLineWidth(1.2)
    c.setDash(4,3) if dashed else c.setDash()
    p=c.beginPath(); p.moveTo(*points[0])
    for v in points[1:]:p.lineTo(*v)
    c.drawPath(p); c.setDash()
    a,b=points[-2:];t=atan2(b[1]-a[1],b[0]-a[0]);r=7
    p=c.beginPath();p.moveTo(*b);p.lineTo(b[0]-r*cos(t-pi/6),b[1]-r*sin(t-pi/6));p.lineTo(b[0]-r*cos(t+pi/6),b[1]-r*sin(t+pi/6));p.close();c.drawPath(p,fill=1,stroke=0)
    if label:text(lx,ly,label,11,MUTED)

